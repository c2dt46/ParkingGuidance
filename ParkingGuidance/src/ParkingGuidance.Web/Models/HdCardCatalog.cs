    public static string? CheckSize(int model, int width, int height)
    {
        if (width > MaxWidth[model] || height > MaxHeight[model])
            return $"{Models[model]} chỉ hỗ trợ tối đa {MaxWidth[model]}×{MaxHeight[model]} px.";
        if ((height / 16) * (width / 32) > MaxBlocks[model])
            return $"Kích thước {width}×{height} vượt số khối tối đa của {Models[model]} ({MaxBlocks[model]} khối 32×16).";
        return null;
    }

