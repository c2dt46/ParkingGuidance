    public static object ToDto() => new
    {
        models = Models.Select((name, i) => new
        {
            index = i, name,
            maxWidth = MaxWidth[i], maxHeight = MaxHeight[i], maxBlocks = MaxBlocks[i],
            colors = ColorOptions(i).Select(c => new { value = c.Value, label = c.Label }),
            grays = Enumerable.Range(0, GrayCount[i]).Select(v => new { value = v, label = GrayLabels[v] }),
            defaultColor = DefaultColor(i)
        }),
        effects = Effects, speeds = Speeds, stopovers = Stopovers, fontSizes = FontSizes, fontTypes = FontTypes,
        digitCounts = DigitCounts, textColors = TextColors,
        maxAreas = MaxAreas
    };
